'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const coach=fs.readFileSync(path.join(root,'prompt-writing-coach.js'),'utf8');
const navigation=fs.readFileSync(path.join(root,'first-screen-navigation.js'),'utf8');
const router=fs.readFileSync(path.join(root,'script.js'),'utf8');

const description='Build clearer, safer, and more useful AI prompts while staying in control of your learning.';
assert.match(navigation,/\['Prompt Coach','promptWithPurpose'\]/,'AI Coach hub must use the existing Prompt Coach view');
